"""Generate RESULTS.md: every arm's metrics at 1, 3 and 5 s for every evaluation JSON.

Dependency-free (json only). Each section: label=path[:tail1,tail2]. For every deadline it
prints the absolute metrics of every arm (median action, plus the mean-action MAE) and the
paired differences against the section's reference arm (the one arm that has no vs_ref
entry), with 95% cluster-bootstrap intervals; bold = interval excludes zero.

  python tailrisk/results_tables.py "INSTANCE, single seeds=results/eval_final_all.json:M>=4,M>=5" ... > tailrisk/RESULTS.md
"""
import json
import sys
from pathlib import Path

DEADLINES = ('1s', '3s', '5s')


def f3(v, nd=3):
    return 'n/a' if v is None or v != v else f'{v:.{nd}f}'


def fd(v, nd=3):
    if v is None or v.get('mean') is None:
        return 'n/a'
    b = '**' if (v['lo'] > 0 or v['hi'] < 0) else ''
    return f"{b}{v['mean']:+.{nd}f} [{v['lo']:+.{nd}f}, {v['hi']:+.{nd}f}]{b}"


def short(arm):
    parts = arm.split('+')
    if len(parts) == 1:
        return arm
    bases = []
    for p in parts:
        b = p.rsplit('_s', 1)[0] if p.rsplit('_s', 1)[-1].isdigit() else p
        if b not in bases:
            bases.append(b)
    return ' + '.join(bases) + f' ({len(parts)} models)'


def section(label, path, tails):
    r = json.loads(Path(path).read_text())
    arms = list(r['arms'])
    ref = [a for a in arms if a not in r.get('vs_ref', {})]
    ref = ref[0] if ref else None
    n = r.get('n_records')
    out = [f'\n## {label}\n', f'Source: `{path}`' + (f'; {n:,} records' if n else '') + (f'; Δ = arm − `{short(ref)}`' if ref else '') + '.\n']
    for d in DEADLINES:
        sample = r['arms'][arms[0]][d]['median_action']
        cols = ['MAE', 'MedAE', 'CVaR95'] + [c for c in (f'{t}_MAE' for t in tails) if c in sample] \
            + [c for c in (f'{t}_eventMAE' for t in tails) if c in sample] + [c for c in (f'{tails[-1]}_bias',) if c in sample] \
            + [c for c in ('FP4_rate',) if c in sample]
        head = ['arm'] + [c.replace('_MAE', ' MAE').replace('_eventMAE', ' event-MAE').replace('_bias', ' bias').replace('FP4_rate', 'false-M4 /10⁴') for c in cols] + ['mean-action MAE', 'NLL', 'CRPS']
        out.append(f'\n### {label} — {d[0]} s, absolute (median action unless stated)\n')
        out.append('| ' + ' | '.join(head) + ' |')
        out.append('|' + '---|' * len(head))
        for a in arms:
            m = r['arms'][a][d]['median_action']
            row = [short(a)] + [f3(m.get(c) * 1e4 if c == 'FP4_rate' and m.get(c) is not None else m.get(c), 1 if c == 'FP4_rate' else 3) for c in cols]
            row += [f3(r['arms'][a][d]['mean_action'].get('MAE')), f3(r['arms'][a][d].get('nll_bin')), f3(r['arms'][a][d].get('crps'))]
            out.append('| ' + ' | '.join(row) + ' |')
        if ref and r.get('vs_ref'):
            any_arm = next(iter(r['vs_ref']))
            dkeys = list(r['vs_ref'][any_arm][d]['median'].keys())
            dcols = [c for c in ['MAE'] + [f'{t}_MAE' for t in tails] + [f'{t}_eventMAE' for t in tails] + ['FP4_rate'] if c in dkeys]
            head = ['arm'] + ['Δ ' + c.replace('_MAE', ' MAE').replace('_eventMAE', ' event-MAE').replace('FP4_rate', 'false-M4 /10⁴') for c in dcols]
            out.append(f'\n### {label} — {d[0]} s, paired differences vs `{short(ref)}` (median action; 95% cluster-bootstrap CI)\n')
            out.append('| ' + ' | '.join(head) + ' |')
            out.append('|' + '---|' * len(head))
            for a, by in r['vs_ref'].items():
                c = by[d]['median']
                cells = []
                for k in dcols:
                    v = c.get(k)
                    if k == 'FP4_rate' and v and v.get('mean') is not None:
                        v = {kk: (vv * 1e4 if kk in ('mean', 'lo', 'hi') else vv) for kk, vv in v.items()}
                        cells.append(fd(v, 1))
                    else:
                        cells.append(fd(v))
                out.append('| ' + short(a) + ' | ' + ' | '.join(cells) + ' |')
            mean_rows = []
            for a, by in r['vs_ref'].items():
                c = by[d].get('mean')
                if c:
                    mean_rows.append('| ' + short(a) + ' | ' + ' | '.join(fd(c.get(k)) for k in dcols if k != 'FP4_rate') + ' |')
            if mean_rows:
                out.append(f'\n*Mean action:*\n')
                out.append('| arm | ' + ' | '.join('Δ ' + c.replace('_MAE', ' MAE').replace('_eventMAE', ' event-MAE') for c in dcols if c != 'FP4_rate') + ' |')
                out.append('|' + '---|' * (1 + len([c for c in dcols if c != 'FP4_rate'])))
                out += mean_rows
    return '\n'.join(out)


def main():
    print('# Detailed results at 1, 3 and 5 s\n')
    print('Generated by `results_tables.py` from the evaluation JSONs in `results/`. Every arm, every '
          'deadline, absolute metrics and paired differences. MAE in magnitude units; bias = mean '
          '(estimate − label) on the tail; false-M4 = share of M<3.5 records estimated ≥ 3.95, per 10⁴; '
          'NLL = negative log-likelihood of the 0.1-wide label bin; CRPS of the predictive CDF. '
          'Ensembles ("k models") average their members\' posteriors. Bold differences have a 95% '
          'cluster-bootstrap interval (1,000 replicates over aftershock sequences) excluding zero.')
    for spec in sys.argv[1:]:
        label, rest = spec.split('=', 1)
        path, tails = rest.split(':', 1)
        print(section(label, path, tails.split(',')))


if __name__ == '__main__':
    main()
